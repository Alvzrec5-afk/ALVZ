const DICTS: Record<Lang, Dict> = { fr, en, pt };

export type T = (key: keyof Dict, vars?: Record<string, string | number>) => string;

/** Fonction de traduction : `t("downloadCollection", { name })`. */
export function translator(lang: Lang): T {
  const d = DICTS[lang] ?? fr;
  return (key, vars) => {
    let s = d[key] ?? fr[key];
    if (vars) for (const [k, v] of Object.entries(vars)) s = s.replaceAll(`{${k}}`, String(v));
    return s;
  };
}

/** Date de l'événement, écrite dans la langue du client (« 12 juin 2026 », « June 12, 2026 », « 12 de junho de 2026 »). */
export function longDate(iso: string | null | undefined, lang: Lang) {
  if (!iso) return "";
  const d = new Date(`${iso.slice(0, 10)}T12:00:00Z`);
  if (Number.isNaN(d.getTime())) return "";
  const locale = lang === "en" ? "en-GB" : lang === "pt" ? "pt-PT" : "fr-FR";
  return new Intl.DateTimeFormat(locale, { day: "numeric", month: "long", year: "numeric", timeZone: "UTC" }).format(d);
}
