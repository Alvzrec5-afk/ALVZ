/**
 * Langue des pages des clients (galerie, vidéo, mot de passe) : celle réglée sur leur téléphone / ordinateur
 * (en-tête Accept-Language du navigateur). Mêmes langues que le site alvzrec.com : français, anglais, portugais.
 * Une autre langue → anglais ; pas d'information → français. Le studio reste en français.
 */
export type Lang = "fr" | "en" | "pt";

export function pickLang(acceptLanguage: string | null | undefined): Lang {
  if (!acceptLanguage) return "fr";
  // « pt-BR,pt;q=0.9,en;q=0.8 » : langues dans l'ordre de préférence de l'appareil.
  const wanted = acceptLanguage
    .split(",")
    .map((part) => {
      const [tag, q] = part.trim().split(";q=");
      return { tag: tag.toLowerCase(), q: q ? Number(q) || 0 : 1 };
    })
    .filter((x) => x.tag)
    .sort((a, b) => b.q - a.q);
  for (const { tag } of wanted) {
    const base = tag.split("-")[0];
    if (base === "fr" || base === "en" || base === "pt") return base;
    if (base === "kea") return "pt"; // créole cap-verdien : le portugais est la langue écrite la plus proche
  }
  return wanted.length ? "en" : "fr";
}

